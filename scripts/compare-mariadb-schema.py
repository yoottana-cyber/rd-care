#!/usr/bin/env python3
"""RD CONNECT SQLite -> MariaDB: OFFLINE, READ-ONLY schema name comparator.

Input 1: JSON generated by sqlite-backup-inventory.py --report.
Input 2: CSV exported from phpMyAdmin with TABLE_NAME,COLUMN_NAME,DATA_TYPE,IS_NULLABLE,EXTRA.
Compares only table and column names. Does not connect to DB servers or open
student records. Matching names DO NOT establish type/index/constraint parity.
"""
import argparse
import csv
import json
import re
import sys
from pathlib import Path

EXPECTED_FORMAT = "rd-connect-sqlite-backup-inventory-v1"
IDENTIFIER = re.compile(r"^[A-Za-z_][A-Za-z0-9_]{0,63}$")
REQUIRED_CSV = {"TABLE_NAME", "COLUMN_NAME", "DATA_TYPE", "IS_NULLABLE", "EXTRA"}


def load_sqlite_report(filename):
    with Path(filename).open(encoding="utf-8-sig") as stream:
        data = json.load(stream)
    if data.get("format") != EXPECTED_FORMAT:
        raise ValueError("sqlite_inventory_report_required")
    if data.get("sqlite_integrity") != "ok" or data.get("sqlite_foreign_keys") != "ok":
        raise ValueError("sqlite_inventory_integrity_not_verified")
    tables = data.get("tables")
    if not isinstance(tables, list) or len(tables) != 63:
        raise ValueError("sqlite_inventory_table_count_invalid")
    names = {}
    for table in tables:
        name = table.get("table")
        cols = table.get("columns")
        if not isinstance(name, str) or not IDENTIFIER.fullmatch(name) or name in names:
            raise ValueError("sqlite_inventory_duplicate_or_invalid_table")
        if not isinstance(cols, list) or not cols:
            raise ValueError("sqlite_inventory_columns_missing")
        column_names = []
        for col in cols:
            cname = col.get("name")
            if not isinstance(cname, str) or not IDENTIFIER.fullmatch(cname) or cname in column_names:
                raise ValueError("sqlite_inventory_invalid_column_name")
            column_names.append(cname)
        names[name] = set(column_names)
    return names


def load_mariadb_csv(filename):
    with Path(filename).open(encoding="utf-8-sig", newline="") as stream:
        # phpMyAdmin export should use comma-separated CSV with header.
        reader = csv.DictReader(stream)
        if not reader.fieldnames:
            raise ValueError("mariadb_csv_header_missing")
        reader.fieldnames = [x.strip().strip("\ufeff") for x in reader.fieldnames]
        if not REQUIRED_CSV.issubset(reader.fieldnames):
            raise ValueError("mariadb_csv_columns_required")
        names = {}
        for row in reader:
            if row.get(None) is not None:
                raise ValueError("mariadb_csv_invalid_columns")
            name = (row.get("TABLE_NAME") or "").strip()
            column = (row.get("COLUMN_NAME") or "").strip()
            if not IDENTIFIER.fullmatch(name) or not IDENTIFIER.fullmatch(column):
                raise ValueError("mariadb_csv_invalid_identifier")
            if not (row.get("DATA_TYPE") or "").strip():
                raise ValueError("mariadb_csv_invalid_data_type")
            if (row.get("IS_NULLABLE") or "").upper() not in ("YES", "NO"):
                raise ValueError("mariadb_csv_nullable_invalid")
            if name not in names:
                names[name] = set()
            if column in names[name]:
                raise ValueError("mariadb_csv_duplicate_column")
            names[name].add(column)
    if len(names) != 63:
        raise ValueError("mariadb_csv_table_count_invalid")
    return names


def compare(source, target):
    source_tables = set(source)
    target_tables = set(target)
    missing_tables = sorted(source_tables - target_tables)
    extra_tables = sorted(target_tables - source_tables)
    missing_columns = {
        name: sorted(source[name] - target[name])
        for name in sorted(source_tables & target_tables)
        if source[name] - target[name]
    }
    extra_columns = {
        name: sorted(target[name] - source[name])
        for name in sorted(source_tables & target_tables)
        if target[name] - source[name]
    }
    return {
        "source_tables": len(source_tables),
        "target_tables": len(target_tables),
        "missing_tables": missing_tables,
        "extra_tables": extra_tables,
        "missing_columns": missing_columns,
        "extra_columns": extra_columns,
        "table_and_column_names_match": not (
            missing_tables or extra_tables or missing_columns or extra_columns
        ),
    }


def main():
    parser = argparse.ArgumentParser(
        description="RD CONNECT: offline SQLite / MariaDB names-only schema comparison"
    )
    parser.add_argument("sqlite_schema_json", help="Read-only inventory JSON")
    parser.add_argument("mariadb_columns_csv", help="Information_schema.COLUMNS CSV")
    args = parser.parse_args()
    try:
        result = compare(
            load_sqlite_report(args.sqlite_schema_json),
            load_mariadb_csv(args.mariadb_columns_csv),
        )
    except (ValueError, OSError, UnicodeError, csv.Error, json.JSONDecodeError) as exc:
        allowed = {
            "sqlite_inventory_report_required",
            "sqlite_inventory_integrity_not_verified",
            "sqlite_inventory_table_count_invalid",
            "sqlite_inventory_duplicate_or_invalid_table",
            "sqlite_inventory_columns_missing",
            "sqlite_inventory_invalid_column_name",
            "mariadb_csv_header_missing",
            "mariadb_csv_columns_required",
            "mariadb_csv_invalid_columns",
            "mariadb_csv_invalid_identifier",
            "mariadb_csv_invalid_data_type",
            "mariadb_csv_nullable_invalid",
            "mariadb_csv_duplicate_column",
            "mariadb_csv_table_count_invalid",
        }
        reason = str(exc)
        print("SCHEMA CHECK BLOCKED: " +
              (reason if reason in allowed else "cannot_read_schema_metadata"),
              file=sys.stderr)
        return 1
    print("RD CONNECT OFFLINE SQLITE -> MARIADB SCHEMA CHECK")
    print("SOURCE TABLES:", result["source_tables"],
          "| TARGET TABLES:", result["target_tables"])
    for name in ("missing_tables", "extra_tables"):
        print(name.upper() + ":", len(result[name]))
        for value in result[name]:
            print("  -", value)
    for name in ("missing_columns", "extra_columns"):
        print(name.upper() + ":", sum(len(v) for v in result[name].values()))
        for table, columns in result[name].items():
            print("  - " + table + ": " + ", ".join(columns))
    print("TABLE/COLUMN NAMES:", "MATCH" if result["table_and_column_names_match"] else "MISMATCH")
    print("NOT VERIFIED: data types, defaults, indexes, triggers, constraints, row counts.")
    print("NO DATABASE CONNECTED; NO STUDENT DATA EXPORTED; NO MIGRATION EXECUTED.")
    return 0 if result["table_and_column_names_match"] else 2


if __name__ == "__main__":
    sys.exit(main())
